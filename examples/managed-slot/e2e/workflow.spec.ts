import { expect, test } from '@playwright/test';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { startServer } from '../server.mjs';

test.setTimeout(60_000);
const base = 'http://127.0.0.1:4194';
const owner = 'managed-e2e-owner-token-0123456789abcdef';
const agent = 'managed-e2e-agent-token-0123456789abcdef';
const source = (version: string, expiresAt = Date.now() + 90_000) => ({ id: 'cms', version, expiresAt, data: { price: '¥99' } });
const tree = (title: string) => ({ component: 'card', props: { title, price: '¥99', link: 'https://example.com/product' } });
let directory: string;
let sourceFile: string;
let running: Awaited<ReturnType<typeof startServer>>;
let initialSource: ReturnType<typeof source>;

test.beforeAll(async () => {
  directory = await mkdtemp(join(tmpdir(), 'managed-e2e-'));
  sourceFile = join(directory, 'source.json');
  initialSource = source('s1');
  await writeFile(sourceFile, JSON.stringify(initialSource));
  running = await startServer({ AI_SLOT_DATA_DIR: join(directory, 'state'), AI_SLOT_SOURCE_FILE: sourceFile,
    AI_SLOT_OWNER_TOKEN: owner, AI_SLOT_AGENT_TOKEN: agent });
});
test.afterAll(async () => { await running?.close(); if (directory) await rm(directory, { recursive: true, force: true }); });

test('人工预览批准、发布、冲突和回滚均通过真实页面', async ({ page, request, browser }) => {
  const publicPage = await browser.newPage();
  try {
    await publicPage.goto('/index.html');
    const slot = publicPage.locator('ai-slot[name="hero"]');
    await expect(slot).toContainText('产品介绍暂不可用');
    await page.goto('/admin.html');
    await expect(page.getByRole('button', { name: '批准' })).toBeDisabled();
    const smallWidth = page.getByRole('radio', { name: '320 px' });
    await smallWidth.focus();
    await page.keyboard.press('Space');
    await expect(smallWidth).toBeChecked();
    await expect(page.locator('#preview')).toHaveCSS('width', '320px');
    await expect(page.locator('#renderer-version')).toContainText('v1');
    await page.getByLabel('Owner 令牌').fill(owner);
    await page.getByLabel('组件树 JSON').fill(JSON.stringify(tree('第一版')));
    await page.getByLabel('来源版本').fill('s1');
    await page.getByRole('button', { name: '创建草稿' }).click();
    await expect(page.locator('#status')).toContainText('草稿已准备');
    await page.getByRole('button', { name: '预览' }).click();
    await expect(page.locator('#preview h2')).toHaveText('第一版');
    await expect(page.locator('#candidate-json')).toContainText('第一版');
    const previewedDraft = await page.getByLabel('草稿 ID').inputValue();
    await page.getByLabel('草稿 ID').fill('unknown-draft');
    await expect(page.getByRole('button', { name: '批准' })).toBeDisabled();
    await page.getByLabel('草稿 ID').fill(previewedDraft);
    await page.getByRole('button', { name: '预览' }).click();
    await expect(page.locator('#preview h2')).toHaveText('第一版');
    await expect(slot).toContainText('产品介绍暂不可用');
    await page.getByRole('button', { name: '批准' }).click();
    await expect(page.getByRole('button', { name: '发布' })).toBeEnabled();
    await expect(slot).toContainText('产品介绍暂不可用');
    await page.getByRole('button', { name: '发布' }).click();
    await expect(slot.locator('h2')).toHaveText('第一版');
    const html = await (await request.get(`${base}/index.html`)).text();
    const registry = await (await request.get(`${base}/registry.json`)).text();
    expect(html + registry).not.toContain(owner);
    const delivery = await (await request.get(`${base}/ai-render/hero`)).text();
    expect(delivery).not.toContain(owner);

    await page.getByLabel('组件树 JSON').fill(JSON.stringify(tree('旧来源草稿')));
    const firstDraft = await page.getByLabel('草稿 ID').inputValue();
    await page.getByRole('button', { name: '创建草稿' }).click();
    await expect(page.getByLabel('草稿 ID')).not.toHaveValue(firstDraft);
    await page.getByRole('button', { name: '预览' }).click();
    await expect(page.locator('#preview h2')).toHaveText('旧来源草稿');
    await page.getByRole('button', { name: '批准' }).click();
    await expect(page.getByRole('button', { name: '发布' })).toBeEnabled();
    await writeFile(sourceFile, JSON.stringify(source('s2')));
    const conflict = page.waitForResponse(response => response.url().endsWith('/ops/publish'));
    await page.getByRole('button', { name: '发布' }).click();
    expect((await conflict).status()).toBe(409);
    await expect(page.locator('#status')).toContainText('source_changed');
    await publicPage.reload();
    await expect(slot).toContainText('产品介绍暂不可用');

    await writeFile(sourceFile, JSON.stringify(initialSource));
    await page.getByLabel('来源版本').fill('s1');
    await page.getByLabel('组件树 JSON').fill(JSON.stringify(tree('第二版')));
    const staleDraft = await page.getByLabel('草稿 ID').inputValue();
    await page.getByRole('button', { name: '创建草稿' }).click();
    await expect(page.getByLabel('草稿 ID')).not.toHaveValue(staleDraft);
    await page.getByRole('button', { name: '预览' }).click();
    await expect(page.locator('#preview h2')).toHaveText('第二版');
    await page.getByLabel('组件树 JSON').fill(JSON.stringify(tree('未经预览的修改')));
    await page.getByRole('button', { name: '批准' }).click();
    await expect(page.getByRole('button', { name: '发布' })).toBeEnabled();
    await page.getByRole('button', { name: '发布' }).click();
    await expect(slot.locator('h2')).toHaveText('第二版');
    await page.getByLabel('目标修订').fill('1');
    const secondDraft = await page.getByLabel('草稿 ID').inputValue();
    await page.getByRole('button', { name: '准备回滚' }).click();
    await expect(page.getByLabel('草稿 ID')).not.toHaveValue(secondDraft);
    await page.getByRole('button', { name: '预览' }).click();
    await expect(page.locator('#preview h2')).toHaveText('第一版');
    await page.getByRole('button', { name: '批准' }).click();
    await expect(page.getByRole('button', { name: '回滚', exact: true })).toBeEnabled();
    await page.getByRole('button', { name: '回滚', exact: true }).click();
    await expect(slot.locator('h2')).toHaveText('第一版');
    const restored = await (await request.get(`${base}/ai-render/hero`)).json();
    expect(restored.meta.revision).toBe(3);
    const shortSource = source('s3', Date.now() + 6_000);
    await writeFile(sourceFile, JSON.stringify(shortSource));
    await publicPage.reload();
    await expect(slot).toContainText('产品介绍暂不可用');
    await page.getByLabel('来源版本').fill('s3');
    await page.getByLabel('组件树 JSON').fill(JSON.stringify(tree('短有效期版')));
    const rollbackDraft = await page.getByLabel('草稿 ID').inputValue();
    await page.getByRole('button', { name: '创建草稿' }).click();
    await expect(page.getByLabel('草稿 ID')).not.toHaveValue(rollbackDraft);
    await page.getByRole('button', { name: '预览' }).click();
    await expect(page.locator('#preview h2')).toHaveText('短有效期版');
    await page.getByRole('button', { name: '批准' }).click();
    await expect(page.getByRole('button', { name: '发布' })).toBeEnabled();
    await page.getByRole('button', { name: '发布' }).click();
    await expect(slot.locator('h2')).toHaveText('短有效期版');
    await expect(slot).toContainText('产品介绍暂不可用', { timeout: 9_000 });
  } finally { await publicPage.close(); }
});
